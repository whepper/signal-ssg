/// Effective feed item cap: configured `[feed] limit`, else the default.
/// Shared by feed resolution and feed digest computation.
pub(crate) fn feed_limit(config: &SignalConfig) -> usize {
    config
        .feed
        .as_ref()
        .and_then(|f| f.limit)
        .filter(|limit| *limit > 0)
        .unwrap_or(signal_core::DEFAULT_FEED_LIMIT)
}

/// Find the collection owning a section route by matching configured route
/// prefixes, falling back to the section-root entry at that route.
pub(crate) fn collection_for_section_route(
    config: &SignalConfig,
    model: &SiteModel,
    route: &Route,
) -> Option<String> {
    let mut names: Vec<&String> = config.collections.keys().collect();
    names.sort();
    for name in names {
        if config.route_prefix_for(name) == route.0 {
            return Some(name.clone());
        }
    }
    model
        .lookup_by_route(route)
        .map(|entry| entry.collection.0.clone())
}

/// Query keys name a projection family plus its exact parameters. Families
/// are fixed and disjoint, so concatenation is unambiguous: parameters
/// cannot change the family, and distinct parameters give distinct keys
/// within a family.
pub mod query_key {
    /// `summaries:{collection}` — `collection_summaries` (date-formatted).
    pub fn summaries(collection: &str) -> String {
        format!("summaries:{collection}")
    }
    /// `home:{collection}` — featured pick + recent list.
    pub fn home(collection: &str) -> String {
        format!("home:{collection}")
    }
    /// `topic_terms` — all topic terms with members.
    pub fn topic_terms() -> String {
        "topic_terms".to_string()
    }
    /// `tagged:{label}` — tag members newest-first (exact label).
    pub fn tagged(label: &str) -> String {
        format!("tagged:{label}")
    }
    /// `feed:main` — capped main-feed items.
    pub fn feed_main() -> String {
        "feed:main".to_string()
    }
    /// `feed:term:{slug}` — capped items for one term.
    pub fn feed_term(slug: &str) -> String {
        format!("feed:term:{slug}")
    }
    /// `routes_inventory` — sitemap URL set.
    pub fn routes_inventory() -> String {
        "routes_inventory".to_string()
    }
    /// `search_documents` — all search documents.
    pub fn search_documents() -> String {
        "search_documents".to_string()
    }
}

/// Compute one query digest from the exact projection the artifact consumes.
///
/// Summaries are hashed as full projections (title/date/tags/route…), never
/// as bare ID lists: a title edit changes no membership but must change the
/// digest. Date-formatted fields fold `site.date_format` into listing
/// digests, so a format change correctly invalidates listings.
pub(crate) fn digest_query(
    config: &SignalConfig,
    model: &SiteModel,
    key: &str,
) -> Result<Digest, BuildError> {
    use signal_generators as gen;
    let date_format = config.date_format_str();
    let base = config.site.base_url.as_deref().unwrap_or("");
    // Every branch digests the consumed projection value itself.
    if let Some(collection) = key.strip_prefix("summaries:") {
        let summaries = gen::collection_summaries(
            model,
            &CollectionId::new(collection.to_string()),
            date_format,
        );
        return Ok(digest_json(&summaries));
    }
    if let Some(collection) = key.strip_prefix("home:") {
        let home = Home::new(CollectionId::new(collection.to_string()), HOME_RECENT_LIMIT);
        let projection = (
            home.featured(model, date_format),
            home.recent(model, date_format),
        );
        return Ok(digest_json(&projection));
    }
    if key == "topic_terms" {
        let root = taxonomy_root(config).ok_or_else(|| BuildError::Model {
            message: "topic_terms query without taxonomy configuration".to_string(),
        })?;
        let terms = gen::topic_terms(model, &root, date_format).map_err(|e| BuildError::Model {
            message: e.to_string(),
        })?;
        return Ok(digest_json(&terms));
    }
    if let Some(label) = key.strip_prefix("tagged:") {
        return Ok(digest_json(&gen::tagged_summaries(
            model,
            label,
            date_format,
        )));
    }
    if key == "feed:main" {
        return Ok(digest_json(
            &MainFeed::new(feed_limit(config)).items(model, base),
        ));
    }
    if let Some(slug) = key.strip_prefix("feed:term:") {
        let root = taxonomy_root(config).ok_or_else(|| BuildError::Model {
            message: "term feed query without taxonomy configuration".to_string(),
        })?;
        let terms = gen::topic_terms(model, &root, date_format).map_err(|e| BuildError::Model {
            message: e.to_string(),
        })?;
        let label = terms
            .iter()
            .find(|t| t.slug == slug)
            .map(|t| t.label.clone())
            .ok_or_else(|| BuildError::Model {
                message: format!("no topic with slug {slug:?}"),
            })?;
        let feeds = TaxonomyFeeds::new(root, feed_limit(config));
        return Ok(digest_json(&feeds.term_items(model, &label, base)));
    }
    if key == "routes_inventory" {
        let sections: Vec<String> = {
            let mut names: Vec<&String> = config.collections.keys().collect();
            names.sort();
            names
                .iter()
                .map(|name| config.route_prefix_for(name))
                .collect()
        };
        return Ok(digest_json(&gen::sitemap::sitemap_urls(
            model,
            base,
            config.site.home_collection.is_some(),
            &sections,
            taxonomy_root(config).as_deref(),
        )));
    }
    if key == "search_documents" {
        return Ok(digest_json(&gen::search::search_documents(model)));
    }
    Err(BuildError::Model {
        message: format!("unknown query key {key:?}"),
    })
}

/// Canonical digest of the whole configuration (coarse by design).
pub(crate) fn config_digest(config: &SignalConfig) -> Digest {
    digest_json(config)
}

/// Current template digests from the loaded renderer.
pub(crate) fn template_digests(
    renderer: &signal_render::MiniJinjaRenderer,
) -> Result<BTreeMap<String, Digest>, BuildError> {
    let mut templates = BTreeMap::new();
    for name in renderer.template_names() {
        let source = renderer
            .template_source(&name)
            .ok_or_else(|| BuildError::Model {
                message: format!("template {name:?} vanished during build"),
            })?;
        templates.insert(name, digest_bytes(source.as_bytes()));
    }
    Ok(templates)
}

/// Canonical form of an input list: each reference serialized, then sorted.
///
/// Both sides of a comparison go through this, so construction-order
/// differences can never cause false invalidations — only genuinely
/// different dependency sets mismatch.
fn canonical_inputs(inputs: &[InputRef]) -> Vec<String> {
    let mut keys: Vec<String> = inputs
        .iter()
        .map(|input| serde_json::to_string(input).expect("owned inputs always serialize"))
        .collect();
    keys.sort();
    keys
}

/// Digest one input reference against current build state.
///
/// `templates` and `config_digest` are precomputed once per build; entries
/// and queries digest on demand from the model. Static sources hash their
/// current bytes. Any failure (missing data, unreadable source) is an
/// error the caller treats as "cannot prove unchanged" — never as success.
fn current_input_digest(
    config: &SignalConfig,
    root: &Path,
    model: &SiteModel,
    templates: &BTreeMap<String, Digest>,
    config_digest: &Digest,
    input: &InputRef,
) -> Result<Digest, BuildError> {
    match input {
        InputRef::Entry { route } => {
            let entry = model
                .lookup_by_route(&Route::new(route.clone()))
                .ok_or_else(|| BuildError::Model {
                    message: format!("no entry for route {route}"),
                })?;
            Ok(entry_digest(entry))
        }
        InputRef::Query { key } => digest_query(config, model, key),
        InputRef::Template { name } => {
            templates
                .get(name)
                .cloned()
                .ok_or_else(|| BuildError::Model {
                    message: format!("template {name:?} not loaded"),
                })
        }
        InputRef::TemplateSet => Ok(digest_json(templates)),
        InputRef::Config => Ok(config_digest.clone()),
        InputRef::Static { path } => {
            // Static resolve reads `static/<path>` under the site root;
            // digest the same bytes. (Containment holds: spec paths passed
            // plan validation, and this join never escapes `static/` for
            // validated components.)
            let source = root.join("static").join(path);
            std::fs::read(&source).map_err(|e| BuildError::Read {
                path: source.display().to_string(),
                message: e.to_string(),
            })
        }
        .map(|bytes| digest_bytes(&bytes)),
    }
}

/// Derive one artifact's input references from its spec, config, and model.
///
/// Mirrors `resolve_artifact` exactly: entry pages name their entry; listings
/// name their query; feeds name feed queries; statics name their source.
/// Every template-rendered artifact names the complete loaded template set
/// (`TemplateSet`, slice 14C) and `Config` (menus, formats, titles, URLs all
/// flow from it); the search index names only its query (it consumes no
/// config).
fn artifact_inputs(
    spec: &ArtifactSpec,
    config: &SignalConfig,
    model: &SiteModel,
) -> Result<Vec<InputRef>, BuildError> {
    use signal_core::ArtifactKind;
    match spec.kind {
        ArtifactKind::Page => {
            let route = spec.route.as_ref().ok_or_else(|| BuildError::Model {
                message: format!("artifact {:?} has no route", spec.path),
            })?;
            let entry = model
                .lookup_by_route(route)
                .ok_or_else(|| BuildError::Model {
                    message: format!("no entry for route {route}"),
                })?;
            Ok(vec![
                InputRef::Entry {
                    route: entry.route.0.clone(),
                },
                InputRef::TemplateSet,
                InputRef::Config,
            ])
        }
        ArtifactKind::CollectionIndex => {
            let route = spec.route.as_ref().ok_or_else(|| BuildError::Model {
                message: format!("artifact {:?} has no route", spec.path),
            })?;
            let collection =
                collection_for_section_route(config, model, route).ok_or_else(|| {
                    BuildError::Model {
                        message: format!("no collection for section route {route}"),
                    }
                })?;
            let mut inputs = vec![
                InputRef::Query {
                    key: query_key::summaries(&collection),
                },
                InputRef::TemplateSet,
                InputRef::Config,
            ];
            if model.lookup_by_route(route).is_some() {
                inputs.insert(
                    0,
                    InputRef::Entry {
                        route: route.0.clone(),
                    },
                );
            }
            Ok(inputs)
        }
        ArtifactKind::Home => {
            let collection =
                config
                    .site
                    .home_collection
                    .clone()
                    .ok_or_else(|| BuildError::Model {
                        message: "home artifact without home configuration".to_string(),
                    })?;
            Ok(vec![
                InputRef::Query {
                    key: query_key::home(&collection),
                },
                InputRef::TemplateSet,
                InputRef::Config,
            ])
        }
        ArtifactKind::Taxonomy => {
            let route = spec.route.as_ref().ok_or_else(|| BuildError::Model {
                message: format!("artifact {:?} has no route", spec.path),
            })?;
            let tax_root = taxonomy_root(config).ok_or_else(|| BuildError::Model {
                message: "taxonomy artifact without taxonomy configuration".to_string(),
            })?;
            if route.0 == tax_root {
                Ok(vec![
                    InputRef::Query {
                        key: query_key::topic_terms(),
                    },
                    InputRef::TemplateSet,
                    InputRef::Config,
                ])
            } else {
                let terms =
                    signal_generators::topic_terms(model, &tax_root, config.date_format_str())
                        .map_err(|e| BuildError::Model {
                            message: e.to_string(),
                        })?;
                let term =
                    terms
                        .iter()
                        .find(|t| t.route == route.0)
                        .ok_or_else(|| BuildError::Model {
                            message: format!("no topic for route {route}"),
                        })?;
                Ok(vec![
                    InputRef::Query {
                        key: query_key::tagged(&term.label),
                    },
                    InputRef::TemplateSet,
                    InputRef::Config,
                ])
            }
        }
        ArtifactKind::Rss => {
            if spec.path == "index.xml" {
                Ok(vec![
                    InputRef::Query {
                        key: query_key::feed_main(),
                    },
                    InputRef::Config,
                ])
            } else {
                let slug = spec
                    .path
                    .strip_suffix("/index.xml")
                    .and_then(|p| p.rsplit('/').next())
                    .ok_or_else(|| BuildError::Model {
                        message: format!("malformed feed path {:?}", spec.path),
                    })?;
                Ok(vec![
                    InputRef::Query {
                        key: query_key::feed_term(slug),
                    },
                    InputRef::Config,
                ])
            }
        }
        ArtifactKind::Sitemap => Ok(vec![
            InputRef::Query {
                key: query_key::routes_inventory(),
            },
            InputRef::Config,
        ]),
        ArtifactKind::SearchIndex => Ok(vec![InputRef::Query {
            key: query_key::search_documents(),
        }]),
        ArtifactKind::Static => Ok(vec![InputRef::Static {
            path: spec.path.clone(),
        }]),
    }
}

/// Compute stale artifact paths: previous manifest records absent from the
/// current plan, sorted.
///
/// Pure inventory subtraction on normalized artifact paths — no filesystem
/// access, no dependency analysis, no graph. The caller decides what to do
/// with the result; this function only identifies it deterministically.
pub(crate) fn stale_artifact_paths(prev: &Manifest, specs: &[ArtifactSpec]) -> Vec<String> {
    let current: BTreeSet<&str> = specs.iter().map(|spec| spec.path.as_str()).collect();
    prev.artifacts
        .keys()
        .filter(|path| !current.contains(path.as_str()))
        .cloned()
        .collect()
}

/// Build the complete manifest for a finished plan.
///
/// `outputs` maps each spec path to the SHA-256 of its exact written bytes
/// (collected during the resolve/write loop — never re-read, never
/// re-resolved). Every planned spec must have exactly one output digest;
/// every output digest must belong to a planned spec.
pub fn build_manifest(
    config: &SignalConfig,
    model: &SiteModel,
    renderer: &signal_render::MiniJinjaRenderer,
    specs: &[ArtifactSpec],
    outputs: &BTreeMap<String, Digest>,
) -> Result<Manifest, BuildError> {
    if specs.len() != outputs.len() {
        return Err(BuildError::Model {
            message: format!(
                "manifest needs one output digest per spec: {} specs, {} digests",
                specs.len(),
                outputs.len()
            ),
        });
    }
    let mut needed_queries = BTreeSet::new();
    let mut records = BTreeMap::new();
    for spec in specs {
        let output_digest = outputs.get(&spec.path).ok_or_else(|| BuildError::Model {
            message: format!("no output digest for planned artifact {:?}", spec.path),
        })?;
        let inputs = artifact_inputs(spec, config, model)?;
        for input in &inputs {
            if let InputRef::Query { key } = input {
                needed_queries.insert(key.clone());
            }
        }
        if records
            .insert(
                spec.path.clone(),
                ArtifactRecord {
                    kind: spec.kind.clone(),
                    route: spec.route.as_ref().map(|r| r.0.clone()),
                    inputs,
                    output_digest: output_digest.clone(),
                },
            )
            .is_some()
        {
            return Err(BuildError::Model {
                message: format!("duplicate manifest record for {:?}", spec.path),
            });
        }
    }

    let mut queries = BTreeMap::new();
    for key in needed_queries {
        queries.insert(key.clone(), digest_query(config, model, &key)?);
    }
    let mut entries = BTreeMap::new();
    for entry in model.entries() {
        entries.insert(entry.route.0.clone(), entry_digest(entry));
    }

    Ok(Manifest {
        schema_version: MANIFEST_SCHEMA_VERSION,
        generation: Some(current_generation()),
        config_digest: config_digest(config),
        templates: template_digests(renderer)?,
        entries,
        queries,
        artifacts: records,
    })
}

/// Previous build state, for reuse decisions.
///
/// The manifest is untrusted metadata: every variant except a fully
/// validated `Usable` manifest leads to a full build, never to reuse.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PreviousManifest {
    /// No manifest file exists: first build.
    Absent,
    /// A manifest exists but must not drive reuse.
    Unusable {
        /// Why: corrupt JSON, unreadable file, unsupported schema, …
        reason: String,
    },
    /// A same-schema manifest whose records may be consulted.
    Usable(Manifest),
}

/// Load the previous manifest without trusting it.
///
/// Missing file → `Absent`. Unreadable file, invalid JSON, or an
/// unsupported `schema_version` → `Unusable` (the build falls back to full;
/// a valid site never fails merely because stale metadata is unusable).
/// Newer schemas are never interpreted as v1.
pub fn load_previous(out_dir: &Path) -> PreviousManifest {
    let path = out_dir.join(MANIFEST_DIR).join(MANIFEST_FILE);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return PreviousManifest::Absent;
        }
        Err(e) => {
            return PreviousManifest::Unusable {
                reason: format!("cannot read {}: {e}", path.display()),
            };
        }
    };
    let manifest = match parse_manifest(&text) {
        Ok(manifest) => manifest,
        Err(e) => {
            return PreviousManifest::Unusable {
                reason: format!("invalid manifest JSON: {e}"),
            };
        }
    };
    if manifest.schema_version != MANIFEST_SCHEMA_VERSION {
        return PreviousManifest::Unusable {
            reason: format!("unsupported manifest schema {}", manifest.schema_version),
        };
    }
    PreviousManifest::Usable(manifest)
}

/// Digest the existing output file, if it is a regular file.
///
/// Directories, symlinks, and missing or unreadable files yield `None`
/// (→ rebuild). Never trusts mtime or size: only exact bytes.
fn existing_output_digest(out_dir: &Path, relative: &str) -> Option<Digest> {
    let path = out_dir.join(relative);
    let file_type = std::fs::symlink_metadata(&path).ok()?.file_type();
    if !file_type.is_file() {
        return None;
    }
    let bytes = std::fs::read(&path).ok()?;
    Some(digest_bytes(&bytes))
}

/// Whether `prev` was produced by generation behavior compatible with the
/// currently running Signal.
///
/// Exact match of both the engine version and the maintained behavior version
/// is required. An absent identity (a manifest written before this field
/// existed) is never compatible: compatibility is not inferred from the
/// schema version. A mismatch is an invalidation condition, not an error.
pub(crate) fn generation_compatible(prev: &Manifest) -> bool {
    prev.generation.as_ref() == Some(&current_generation())
}

/// Decide whether one artifact may be reused from a previous manifest.
///
/// Total function: any uncertainty — generation incompatibility, missing
/// record, kind change, input structure or digest mismatch, missing/invalid
/// existing output — returns `false` (rebuild), never an error. Reuse
/// requires ALL of: `prev` was produced by compatible generation behavior,
/// the record exists under this path, the kind matches, the canonical
/// input lists match, every current input digest matches the recorded one,
/// and the existing output file hashes to the recorded output digest.
///
/// `templates` and `config_digest` are precomputed once per build and
/// shared across artifacts; per-artifact work is its own inputs plus one
/// output read. Takes `&SiteModel` read-only; touches the filesystem only
/// to validate the one output file. Lookup keys are always current spec
/// paths, so corrupt manifest paths can never redirect a read or a write.
#[allow(clippy::too_many_arguments)]
pub(crate) fn artifact_reusable(
    spec: &ArtifactSpec,
    config: &SignalConfig,
    root: &Path,
    model: &SiteModel,
    templates: &BTreeMap<String, Digest>,
    config_digest: &Digest,
    prev: &Manifest,
    out_dir: &Path,
) -> bool {
    // Build-wide compatibility gate: generation behavior is not an artifact
    // dependency, so it is checked before any per-artifact input comparison.
    if !generation_compatible(prev) {
        return false;
    }
    let record = match prev.artifacts.get(&spec.path) {
        Some(record) => record,
        None => return false,
    };
    if record.kind != spec.kind {
        return false;
    }
    let current_inputs = match artifact_inputs(spec, config, model) {
        Ok(inputs) => inputs,
        Err(_) => return false,
    };
    if canonical_inputs(&current_inputs) != canonical_inputs(&record.inputs) {
        return false;
    }
    // The recorded complete template set, digested once for `TemplateSet`
    // inputs (slice 14C).
    let previous_template_set = digest_json(&prev.templates);
    for input in &current_inputs {
        let current =
            match current_input_digest(config, root, model, templates, config_digest, input) {
                Ok(digest) => digest,
                Err(_) => return false,
            };
        let previous = match input {
            InputRef::Entry { route } => prev.entries.get(route),
            InputRef::Query { key } => prev.queries.get(key),
            InputRef::Template { name } => prev.templates.get(name),
            InputRef::TemplateSet => Some(&previous_template_set),
            InputRef::Config => Some(&prev.config_digest),
            // Static sources have no digest map: the recorded output
            // digest IS the source digest (verbatim passthrough).
            InputRef::Static { .. } => Some(&record.output_digest),
        };
        if previous != Some(&current) {
            return false;
        }
    }
    match existing_output_digest(out_dir, &spec.path) {
        Some(digest) => digest == record.output_digest,
        None => false,
    }
}

/// Manifest JSON text: pretty-printed for reviewability, matching the
/// project's golden-file conventions.
pub fn manifest_json(manifest: &Manifest) -> String {
    serde_json::to_string_pretty(manifest).expect("owned manifest always serializes")
}

/// Read a manifest back (schema round-trips; behavior never branches on it
/// in this slice).
pub fn parse_manifest(text: &str) -> Result<Manifest, String> {
    serde_json::from_str(text).map_err(|e| e.to_string())
}

/// Write the manifest atomically: temp file in `.signal/` plus rename, so a
/// failed write never replaces the previous manifest with a partial one.
pub fn write_manifest(
    out_dir: &Path,
    manifest: &Manifest,
) -> Result<std::path::PathBuf, BuildError> {
    let dir = out_dir.join(MANIFEST_DIR);
    std::fs::create_dir_all(&dir).map_err(|e| BuildError::Write {
        path: dir.display().to_string(),
        message: e.to_string(),
    })?;
    let dest = dir.join(MANIFEST_FILE);
    let temp = dir.join(format!("{MANIFEST_FILE}.tmp"));
    std::fs::write(&temp, manifest_json(manifest)).map_err(|e| BuildError::Write {
        path: temp.display().to_string(),
        message: e.to_string(),
    })?;
    std::fs::rename(&temp, &dest).map_err(|e| BuildError::Write {
        path: dest.display().to_string(),
        message: e.to_string(),
    })?;
    Ok(dest)
}

