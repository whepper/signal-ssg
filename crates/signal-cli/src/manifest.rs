//! Deterministic build manifest: a truthful record of one complete build.
//!
//! After every successful build, Signal writes `.signal/manifest.json`
//! describing exactly what went in (semantic inputs) and what came out
//! (artifact bytes). The manifest does not influence the build that writes
//! it; the *next* build consults it to reuse unchanged artifacts and to prune
//! stale outputs. It is disposable build state, not a public artifact: never
//! planned, never served, and deleting `.signal/` changes only how much work
//! the next build does, never its correctness.
//!
//! Design rules:
//! - Flat records, no graph: `artifacts[path]` lists its own inputs; there
//!   are no edges to traverse and no DAG to persist.
//! - Digests hash canonical serializations (structs in field order,
//!   `BTreeMap`s, ordered `Vec`s) — never `Debug`, never `HashMap`
//!   iteration, never timestamps, mtimes, or pointers.
//! - Only digests are stored: the manifest can depend on sensitive config
//!   values without containing them.
//!
//! This module also owns the shared deterministic derivations (template
//! selection, taxonomy roots, feed limits) used by both artifact resolution
//! and manifest recording, so the two can never disagree.

