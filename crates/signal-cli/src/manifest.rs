/// Manifest schema version. Bump deliberately on breaking changes.
pub const MANIFEST_SCHEMA_VERSION: u32 = 1;
/// Build-state directory inside the output root. Never served, never planned.
pub const MANIFEST_DIR: &str = ".signal";
/// Manifest filename inside [`MANIFEST_DIR`].
pub const MANIFEST_FILE: &str = "manifest.json";

/// Deliberately maintained version of Signal's output-generating behavior.
///
/// Bump this whenever a change can alter generated bytes without necessarily
/// changing any recorded semantic input: rendering, Markdown transforms,
/// heading anchors, date formatting, reading time, excerpts, RSS/sitemap
/// serialization, search projection, JSON-LD, default rendering contexts,
/// artifact planning that changes output, or asset behavior.
///
/// Do NOT bump it for comments, refactors with byte-identical output,
/// test-only changes, documentation, or output-preserving performance work.
///
/// This is separate from [`MANIFEST_SCHEMA_VERSION`]: the schema says whether
/// the metadata can be read; this says whether previously generated artifacts
/// are semantically eligible for reuse.
///
/// History: `1` covered generation through slice 15B; `2` adds route-to-URL
/// path encoding (slice 15C), which changes feed, sitemap, search, and
/// template-context bytes for routes with URL-significant characters; `3`
/// extends that encoding to front-matter image `src` values and internal
/// menu URLs (slice 15E), which changes page bytes for images and menus
/// with URL-significant characters.
pub const GENERATION_BEHAVIOR_VERSION: u32 = 3;

/// Identity of the code that produced a manifest.
///
/// Both parts participate in the reuse compatibility gate:
/// - `engine_version` is the Cargo package version of the `signal-cli` crate
///   that wrote the manifest (a coarse, released-implementation identity);
/// - `behavior_version` is [`GENERATION_BEHAVIOR_VERSION`], the maintained
///   output-semantics identity.
///
/// The pair is deterministic and carries no machine-specific data. It is a
/// build-wide compatibility condition, never an artifact dependency (it does
/// not appear in any artifact's `inputs`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct GenerationIdentity {
    /// Cargo package version of the Signal implementation.
    pub engine_version: String,
    /// Maintained version of output-generating behavior.
    pub behavior_version: u32,
}

/// The generation identity of the currently running Signal.
pub fn current_generation() -> GenerationIdentity {
    GenerationIdentity {
        engine_version: env!("CARGO_PKG_VERSION").to_string(),
        behavior_version: GENERATION_BEHAVIOR_VERSION,
    }
}

/// Recent entries shown on the home page. Matches the migrated Hugo home
/// grid (`first 8`); a plain cap, not pagination (the site uses none).
pub(crate) const HOME_RECENT_LIMIT: usize = 8;

/// SHA-256 digest rendered as lowercase hex.
///
/// The single digest representation for entries, queries, templates,
/// config, static sources, and outputs. Deterministic, portable, and
/// trivially inspectable.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct Digest(String);

impl Digest {
    /// The hex string.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for Digest {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// SHA-256 over raw bytes (static sources, resolved outputs).
pub fn digest_bytes(bytes: &[u8]) -> Digest {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    Digest(format!("{:x}", hasher.finalize()))
}

/// SHA-256 over a canonical JSON serialization.
///
/// Only pass values with deterministic serialization: structs (field
/// order), `BTreeMap`s (sorted), and `Vec`s in an explicitly deterministic
/// order. Owned serializable data always serializes, so failure here is a
/// bug, not an input error.
pub fn digest_json<T: Serialize>(value: &T) -> Digest {
    let json = serde_json::to_string(value).expect("owned data always serializes");
    digest_bytes(json.as_bytes())
}

/// One semantic input an artifact was resolved from.
///
/// Variants name *what kind* of input, with the key needed to find its
/// digest elsewhere in the manifest (`entries`, `queries`, `templates`) —
/// except `Config`, whose digest is the single `config_digest`, and
/// `Static`, whose source digest equals its artifact's output digest
/// (verbatim passthrough).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum InputRef {
    /// A normalized content entry, keyed by route.
    Entry {
        /// Entry route, e.g. `/posts/alpha/`.
        route: String,
    },
    /// A named projection result, keyed by query key (see query key docs).
    Query {
        /// Query key, e.g. `summaries:posts`.
        key: String,
    },
    /// A template by selected name, e.g. `post.html`.
    ///
    /// Legacy: emitted before slice 14C. Retained so manifests written by
    /// older builds still deserialize; current builds record
    /// [`InputRef::TemplateSet`] instead.
    Template {
        /// Template name.
        name: String,
    },
    /// The complete loaded template set (slice 14C).
    ///
    /// A change to *any* loaded template invalidates every artifact rendered
    /// through templates. This is deliberately coarser than a per-artifact
    /// `{% extends %}` / `{% include %}` closure but is sound, deterministic,
    /// and free of template-source parsing: MiniJinja 2.x caches loaded
    /// templates and exposes no per-render dependency hook, so exact closure
    /// capture would require recompiling the template graph per artifact.
    TemplateSet,
    /// Whole canonical configuration (covers menus, date formats, URLs…).
    Config,
    /// A static source file, relative to `static/`.
    Static {
        /// Source path, e.g. `images/alpha.svg`.
        path: String,
    },
}

/// One built artifact's record: what it is, what went in, what came out.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ArtifactRecord {
    /// Artifact kind, preserved from its spec.
    pub kind: ArtifactKind,
    /// Originating route, if the spec carries one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub route: Option<String>,
    /// Semantic inputs, in deterministic per-family construction order.
    pub inputs: Vec<InputRef>,
    /// SHA-256 of the exact bytes written.
    pub output_digest: Digest,
}

/// A complete, deterministic description of one successful build.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Manifest {
    /// Schema version ([`MANIFEST_SCHEMA_VERSION`]).
    pub schema_version: u32,
    /// Code identity that produced this manifest.
    ///
    /// `None` only for manifests written before this field existed. Those
    /// remain readable (schema-compatible) but are never eligible for reuse:
    /// generation compatibility is never inferred from the schema version.
    #[serde(default)]
    pub generation: Option<GenerationIdentity>,
    /// Digest of the canonical [`SignalConfig`] serialization.
    pub config_digest: Digest,
    /// Every loaded template by name. Records the full loaded set; since
    /// slice 14C template-rendered artifacts depend on the set as a whole
    /// (`InputRef::TemplateSet`), making `{% extends %}` / `{% include %}`
    /// changes invalidate soundly without a template-source parser.
    pub templates: BTreeMap<String, Digest>,
    /// Every model entry by route.
    pub entries: BTreeMap<String, Digest>,
    /// Every consumed projection by query key.
    pub queries: BTreeMap<String, Digest>,
    /// Every planned artifact by output path.
    pub artifacts: BTreeMap<String, ArtifactRecord>,
}

/// Explicit entry digest input: exactly the normalized fields whose changes
/// can alter generated output.
///
/// `translation_group`, `language`, and `references` are excluded: no
/// current artifact consumes them. Adding such a consumer later must add
/// the field here. `ContentId` is excluded: identity is already carried by
/// collection + source path, and the numeric handle adds nothing semantic.
/// The whole `body` is included — entry HTML, TOC, excerpts, and reading
/// time each consume part of it, and splitting it further would be elegance
/// without a consumer.
#[derive(Serialize)]
struct EntryDigestInput<'a> {
    collection: &'a str,
    source_path: &'a str,
    route: &'a str,
    slug: &'a str,
    title: &'a str,
    description: Option<&'a str>,
    date: Option<&'a str>,
    last_modified: Option<&'a str>,
    author: Option<&'a str>,
    image: Option<&'a str>,
    image_alt: Option<&'a str>,
    tags: &'a BTreeSet<String>,
    featured: bool,
    section_root: bool,
    body: &'a signal_core::RenderedBody,
}

/// Digest one normalized entry.
pub fn entry_digest(entry: &ContentEntry) -> Digest {
    digest_json(&EntryDigestInput {
        collection: &entry.collection.0,
        source_path: &entry.source.relative_path,
        route: &entry.route.0,
        slug: &entry.slug.0,
        title: &entry.title,
        description: entry.description.as_deref(),
        date: entry.date.as_deref(),
        last_modified: entry.last_modified.as_deref(),
        author: entry.author.as_deref(),
        image: entry.image.as_deref(),
        image_alt: entry.image_alt.as_deref(),
        tags: &entry.tags,
        featured: entry.featured,
        section_root: entry.section_root,
        body: &entry.body,
    })
}

/// Template selected for an entry's collection.
pub(crate) fn template_for_collection(config: &SignalConfig, collection: &str) -> String {
    config
        .collections
        .get(collection)
        .and_then(|c| c.template.clone())
        .filter(|t| !t.trim().is_empty())
        .unwrap_or_else(|| "post.html".to_string())
}

