/// Normalized taxonomy root route, e.g. `/topics/`.
pub(crate) fn taxonomy_root(config: &SignalConfig) -> Option<String> {
    config.taxonomy.as_ref().map(|t| {
        TopicsIndex::new(
            t.route_prefix
                .clone()
                .filter(|p| !p.trim().is_empty())
                .unwrap_or_else(|| "/topics/".to_string()),
        )
        .root()
        .to_string()
    })
}

