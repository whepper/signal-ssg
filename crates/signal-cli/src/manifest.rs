/// Deliberately maintained version of Signal's output-generating behavior.
///
/// Bump this whenever a change can alter generated bytes without necessarily
/// changing any recorded semantic input: rendering, Markdown transforms,
/// heading anchors, date formatting, reading time, excerpts, RSS/sitemap
/// serialization, search projection, JSON-LD, default rendering contexts,
/// artifact planning that changes output, or asset behavior.
///
/// Do NOT bump it for comments, refactors with byte-identical output,
/// test-only changes, documentation, or output-preserving performance work.
///
/// This is separate from [`MANIFEST_SCHEMA_VERSION`]: the schema says whether
/// the metadata can be read; this says whether previously generated artifacts
/// are semantically eligible for reuse.
///
/// History: `1` covered generation through slice 15B; `2` adds route-to-URL
/// path encoding (slice 15C), which changes feed, sitemap, search, and
/// template-context bytes for routes with URL-significant characters; `3`
/// extends that encoding to front-matter image `src` values and internal
/// menu URLs (slice 15E), which changes page bytes for images and menus
/// with URL-significant characters; `4` adds the `extra` and `related`
/// context keys, ARIA roles on alerts, the Mermaid `<details>` source
/// fallback, and opt-in Git-derived `last_modified`; `5` adds section and
/// taxonomy-label RSS feeds (new `index.xml` artifacts under `[feed]`),
/// opt-in robots.txt (`[robots]`), and the themed 404 artifact
/// (`site.not_found_template`); `6` adds authored topic display order
/// (`tag_order` in entry digests and template-visible tag lists); `7` adds
/// hero `image`/`image_alt` to entry summaries (home heroes, cards, and
/// every listing/term/related projection that embeds them); `8` adds
/// opt-in HTML minification (`[output] minify_html`), a post-render output
/// step that changes HTML bytes when enabled; `9` adds first-class asset
/// edges (A1): page artifacts name their entry's referenced source assets
/// as `Static` inputs, so asset-byte changes invalidate embedding pages;
/// `10` adds generated image derivatives (A2): `DerivedImage` artifacts
/// and derivative inputs on embedding pages, plus the `[images]`
/// configuration they derive from; `11` adds responsive image rendering
/// (A3): body `<img>` tags and the `responsive_image` hero context embed
/// planned derivatives as `srcset`/`sizes`/dimensions on configured
/// sites (unconfigured output is byte-identical, but rendering semantics
/// changed, so the gate rebuilds once); `12` adds the AVIF derivative
/// format and `<picture>` rendering (A4): the `[images]` format set
/// (`format`/`formats`) joins derivative identity, and multi-format plans
/// render `<source>` groups with a WebP-preferring fallback (single-format
/// output is unchanged in shape, but encoder identity and rendering
/// semantics changed, so the gate rebuilds once); `13` adds generated
/// social cards (A5): `[social]` joins the configuration digest, entry
/// pages on enabled sites gain an `og:image`/`twitter:*` card reference,
/// and `SocialImage` artifacts carry the generator's identity (font,
/// layout, encoder). Disabled sites produce byte-identical output but the
/// config shape changed, so the gate rebuilds once. `14` adds WebP as a
/// valid derivative source: configured sites that reference WebP assets now
/// plan derivatives and consume responsive markup through the existing
/// pipeline. Existing PNG/JPEG and disabled-site output is unchanged, but the
/// additional artifacts and page bytes require a one-time compatibility
/// rebuild for affected sites.
pub const GENERATION_BEHAVIOR_VERSION: u32 = 14;

/// Identity of the code that produced a manifest.
///
/// Both parts participate in the reuse compatibility gate:
/// - `engine_version` is the Cargo package version of the `signal-cli` crate
///   that wrote the manifest (a coarse, released-implementation identity);
/// - `behavior_version` is [`GENERATION_BEHAVIOR_VERSION`], the maintained
///   output-semantics identity.
///
/// The pair is deterministic and carries no machine-specific data. It is a
/// build-wide compatibility condition, never an artifact dependency (it does
/// not appear in any artifact's `inputs`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct GenerationIdentity {
    /// Cargo package version of the Signal implementation.
    pub engine_version: String,
    /// Maintained version of output-generating behavior.
    pub behavior_version: u32,
}

/// The generation identity of the currently running Signal.
pub fn current_generation() -> GenerationIdentity {
    GenerationIdentity {
        engine_version: env!("CARGO_PKG_VERSION").to_string(),
        behavior_version: GENERATION_BEHAVIOR_VERSION,
    }
}

