    #[test]
    fn generation_identity_is_deterministic_and_serializable() {
        let first = current_generation();
        let second = current_generation();
        assert_eq!(first, second);
        assert_eq!(first.engine_version, env!("CARGO_PKG_VERSION"));
        assert_eq!(first.behavior_version, GENERATION_BEHAVIOR_VERSION);

        let json = serde_json::to_string(&first).expect("serializes");
        let parsed: GenerationIdentity = serde_json::from_str(&json).expect("round-trips");
        assert_eq!(parsed, first);
        // No machine-specific values, paths, or timestamps.
        for forbidden in ["/Users", "/home", "\\", "2026-", "T00:"] {
            assert!(
                !json.contains(forbidden),
                "identity leaked {forbidden:?}: {json}"
            );
        }
    }

    #[test]
    fn generation_compatibility_requires_an_exact_match() {
        let base = Manifest {
            schema_version: MANIFEST_SCHEMA_VERSION,
            generation: Some(current_generation()),
            config_digest: digest_bytes(b"cfg"),
            templates: BTreeMap::new(),
            entries: BTreeMap::new(),
            queries: BTreeMap::new(),
            artifacts: BTreeMap::new(),
        };
        assert!(generation_compatible(&base));

        // Absent identity (legacy manifest) is never compatible.
        let legacy = Manifest {
            generation: None,
            ..base.clone()
        };
        assert!(!generation_compatible(&legacy));

        // A different behavior version or engine version is incompatible.
        let mut other_behavior = current_generation();
        other_behavior.behavior_version += 1;
        assert!(!generation_compatible(&Manifest {
            generation: Some(other_behavior),
            ..base.clone()
        }));
        let mut other_engine = current_generation();
        other_engine.engine_version = "0.0.0-other".to_string();
        assert!(!generation_compatible(&Manifest {
            generation: Some(other_engine),
            ..base.clone()
        }));
    }
