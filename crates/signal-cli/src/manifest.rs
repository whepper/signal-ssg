/// Compute one query digest from the exact projection the artifact consumes.
///
/// Summaries are hashed as full projections (title/date/tags/route…), never
/// as bare ID lists: a title edit changes no membership but must change the
/// digest. Date-formatted fields fold `site.date_format` into listing
/// digests, so a format change correctly invalidates listings.
pub(crate) fn digest_query(
    config: &SignalConfig,
    model: &SiteModel,
    key: &str,
) -> Result<Digest, BuildError> {
    use signal_generators as gen;
    let date_format = config.date_format_str();
    let base = config.site.base_url.as_deref().unwrap_or("");
    // Every branch digests the consumed projection value itself.
    if let Some(collection) = key.strip_prefix("summaries:") {
        let summaries = gen::collection_summaries(
            model,
            &CollectionId::new(collection.to_string()),
            date_format,
        );
        return Ok(digest_json(&summaries));
    }
    if let Some(collection) = key.strip_prefix("home:") {
        let home = Home::new(CollectionId::new(collection.to_string()), HOME_RECENT_LIMIT);
        let projection = (
            home.featured(model, date_format),
            home.recent(model, date_format),
        );
        return Ok(digest_json(&projection));
    }
    if key == "topic_terms" {
        let root = taxonomy_root(config).ok_or_else(|| BuildError::Model {
            message: "topic_terms query without taxonomy configuration".to_string(),
        })?;
        let terms = gen::topic_terms(model, &root, date_format).map_err(|e| BuildError::Model {
            message: e.to_string(),
        })?;
        return Ok(digest_json(&terms));
    }
    if let Some(label) = key.strip_prefix("tagged:") {
        return Ok(digest_json(&gen::tagged_summaries(
            model,
            label,
            date_format,
        )));
    }
    if let Some(route) = key.strip_prefix("related:") {
        let entry = model
            .lookup_by_route(&signal_core::Route::new(route.to_string()))
            .ok_or_else(|| BuildError::Model {
                message: format!("no entry for route {route}"),
            })?;
        return Ok(digest_json(&gen::related_entries(
            model,
            entry,
            related_limit(config),
            date_format,
        )));
    }
    if key == "feed:main" {
        return Ok(digest_json(
            &MainFeed::new(feed_limit(config)).items(model, base),
        ));
    }
    if let Some(collection) = key.strip_prefix("feed:section:") {
        let prefix = config.route_prefix_for(collection);
        return Ok(digest_json(
            &signal_generators::SectionFeeds::new(
                CollectionId::new(collection.to_string()),
                prefix,
                feed_limit(config),
            )
            .items(model, base),
        ));
    }
    if key == "feed:labels" {
        let root = taxonomy_root(config).ok_or_else(|| BuildError::Model {
            message: "label feed query without taxonomy configuration".to_string(),
        })?;
        return Ok(digest_json(
            &TaxonomyFeeds::new(root, feed_limit(config)).label_items(model, base),
        ));
    }
    if let Some(slug) = key.strip_prefix("feed:term:") {
        let root = taxonomy_root(config).ok_or_else(|| BuildError::Model {
            message: "term feed query without taxonomy configuration".to_string(),
        })?;
        let terms = gen::topic_terms(model, &root, date_format).map_err(|e| BuildError::Model {
            message: e.to_string(),
        })?;
        let label = terms
            .iter()
            .find(|t| t.slug == slug)
            .map(|t| t.label.clone())
            .ok_or_else(|| BuildError::Model {
                message: format!("no topic with slug {slug:?}"),
            })?;
        let feeds = TaxonomyFeeds::new(root, feed_limit(config));
        return Ok(digest_json(&feeds.term_items(model, &label, base)));
    }
    if key == "routes_inventory" {
        let sections: Vec<String> = {
            let mut names: Vec<&String> = config.collections.keys().collect();
            names.sort();
            names
                .iter()
                .map(|name| config.route_prefix_for(name))
                .collect()
        };
        return Ok(digest_json(&gen::sitemap::sitemap_urls(
            model,
            base,
            config.site.home_collection.is_some(),
            &sections,
            taxonomy_root(config).as_deref(),
        )));
    }
    if key == "search_documents" {
        return Ok(digest_json(&gen::search::search_documents(model)));
    }
    Err(BuildError::Model {
        message: format!("unknown query key {key:?}"),
    })
}

/// Look up a source-asset digest: raw form first, then the
/// percent-decoded form — the precedence `link_check` validates with —
/// so authored encoded references match their on-disk records.
pub(crate) fn asset_digest<'a>(
    assets: &'a BTreeMap<String, Digest>,
    path: &str,
) -> Option<&'a Digest> {
    if let Some(digest) = assets.get(path) {
        return Some(digest);
    }
    match signal_core::percent_decode(path) {
        Some(decoded) if decoded != path => assets.get(&decoded),
        _ => None,
    }
}

/// Canonical digest of the whole configuration (coarse by design).
pub(crate) fn config_digest(config: &SignalConfig) -> Digest {
    digest_json(config)
}

/// Current template digests from the loaded renderer.
pub(crate) fn template_digests(
    renderer: &signal_render::MiniJinjaRenderer,
) -> Result<BTreeMap<String, Digest>, BuildError> {
    let mut templates = BTreeMap::new();
    for name in renderer.template_names() {
        let source = renderer
            .template_source(&name)
            .ok_or_else(|| BuildError::Model {
                message: format!("template {name:?} vanished during build"),
            })?;
        templates.insert(name, digest_bytes(source.as_bytes()));
    }
    Ok(templates)
}

/// Derive one artifact's input references: single source of truth lives in
/// [`crate::build_plan::artifact_inputs`]. Canonical input-list form and
/// per-input digests live there too, so planning (reuse decisions) and
/// recording (the new manifest) share one contract. This wrapper keeps
/// manifest recording compiling against that contract.
fn artifact_inputs(
    spec: &ArtifactSpec,
    config: &SignalConfig,
    model: &SiteModel,
) -> Result<Vec<InputRef>, BuildError> {
    crate::build_plan::artifact_inputs(spec, config, model)
}

/// Build the complete manifest for a finished plan.
///
/// `outputs` maps each spec path to the SHA-256 of its exact written bytes
/// (collected during the resolve/write loop — never re-read, never
/// re-resolved). Every planned spec must have exactly one output digest;
/// every output digest must belong to a planned spec.
pub fn build_manifest(
    config: &SignalConfig,
    model: &SiteModel,
    renderer: &signal_render::MiniJinjaRenderer,
    specs: &[ArtifactSpec],
    outputs: &BTreeMap<String, Digest>,
) -> Result<Manifest, BuildError> {
    if specs.len() != outputs.len() {
        return Err(BuildError::Model {
            message: format!(
                "manifest needs one output digest per spec: {} specs, {} digests",
                specs.len(),
                outputs.len()
            ),
        });
    }
    let mut needed_queries = BTreeSet::new();
    let mut records = BTreeMap::new();
    for spec in specs {
        let output_digest = outputs.get(&spec.path).ok_or_else(|| BuildError::Model {
            message: format!("no output digest for planned artifact {:?}", spec.path),
        })?;
        let inputs = artifact_inputs(spec, config, model)?;
        for input in &inputs {
            if let InputRef::Query { key } = input {
                needed_queries.insert(key.clone());
            }
        }
        if records
            .insert(
                spec.path.clone(),
                ArtifactRecord {
                    kind: spec.kind.clone(),
                    route: spec.route.as_ref().map(|r| r.0.clone()),
                    inputs,
                    output_digest: output_digest.clone(),
                },
            )
            .is_some()
        {
            return Err(BuildError::Model {
                message: format!("duplicate manifest record for {:?}", spec.path),
            });
        }
    }

    let mut queries = BTreeMap::new();
    for key in needed_queries {
        queries.insert(key.clone(), digest_query(config, model, &key)?);
    }
    let mut entries = BTreeMap::new();
    for entry in model.entries() {
        entries.insert(entry.route.0.clone(), entry_digest(entry));
    }
    // Source-asset digests for the `Static` inputs pages and sections
    // name: the output digest of a `Static` artifact IS its source digest
    // (verbatim passthrough), so no source re-read is needed.
    let mut assets = BTreeMap::new();
    for spec in specs {
        if spec.kind == ArtifactKind::Static {
            let digest = outputs.get(&spec.path).ok_or_else(|| BuildError::Model {
                message: format!("no output digest for planned artifact {:?}", spec.path),
            })?;
            assets.insert(spec.path.clone(), digest.clone());
        }
    }

    Ok(Manifest {
        schema_version: MANIFEST_SCHEMA_VERSION,
        generation: Some(current_generation()),
        config_digest: config_digest(config),
        templates: template_digests(renderer)?,
        entries,
        queries,
        assets,
        artifacts: records,
    })
}

/// Previous build state, for reuse decisions.
///
/// The manifest is untrusted metadata: every variant except a fully
/// validated `Usable` manifest leads to a full build, never to reuse.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PreviousManifest {
    /// No manifest file exists: first build.
    Absent,
    /// A manifest exists but must not drive reuse.
    Unusable {
        /// Why: corrupt JSON, unreadable file, unsupported schema, …
        reason: String,
    },
    /// A same-schema manifest whose records may be consulted.
    Usable(Manifest),
}

/// Load the previous manifest without trusting it.
///
/// Missing file → `Absent`. Unreadable file, invalid JSON, or an
/// unsupported `schema_version` → `Unusable` (the build falls back to full;
/// a valid site never fails merely because stale metadata is unusable).
/// Newer schemas are never interpreted as v1.
pub fn load_previous(out_dir: &Path) -> PreviousManifest {
    let path = out_dir.join(MANIFEST_DIR).join(MANIFEST_FILE);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return PreviousManifest::Absent;
        }
        Err(e) => {
            return PreviousManifest::Unusable {
                reason: format!("cannot read {}: {e}", path.display()),
            };
        }
    };
    let manifest = match parse_manifest(&text) {
        Ok(manifest) => manifest,
        Err(e) => {
            return PreviousManifest::Unusable {
                reason: format!("invalid manifest JSON: {e}"),
            };
        }
    };
    if manifest.schema_version != MANIFEST_SCHEMA_VERSION {
        return PreviousManifest::Unusable {
            reason: format!("unsupported manifest schema {}", manifest.schema_version),
        };
    }
    PreviousManifest::Usable(manifest)
}

/// Whether `prev` was produced by generation behavior compatible with the
/// currently running Signal.
///
/// Note: the existing-output digest helper lives in [`crate::build_plan`]
/// with the rest of the reuse predicate — directories, symlinks, and
/// missing or unreadable files yield `None` (→ rebuild); mtime and size
/// are never trusted, only exact bytes.
///
/// Exact match of both the engine version and the maintained behavior version
/// is required. An absent identity (a manifest written before this field
/// existed) is never compatible: compatibility is not inferred from the
/// schema version. A mismatch is an invalidation condition, not an error.
pub(crate) fn generation_compatible(prev: &Manifest) -> bool {
    prev.generation.as_ref() == Some(&current_generation())
}

/// Manifest JSON text: pretty-printed for reviewability, matching the
/// project's golden-file conventions.
pub fn manifest_json(manifest: &Manifest) -> String {
    serde_json::to_string_pretty(manifest).expect("owned manifest always serializes")
}

/// Read a manifest back (schema round-trips; behavior never branches on it
/// in this slice).
pub fn parse_manifest(text: &str) -> Result<Manifest, String> {
    serde_json::from_str(text).map_err(|e| e.to_string())
}

/// Write the manifest atomically: temp file in `.signal/` plus rename, so a
/// failed write never replaces the previous manifest with a partial one.
pub fn write_manifest(
    out_dir: &Path,
    manifest: &Manifest,
) -> Result<std::path::PathBuf, BuildError> {
    let dir = out_dir.join(MANIFEST_DIR);
    std::fs::create_dir_all(&dir).map_err(|e| BuildError::Write {
        path: dir.display().to_string(),
        message: e.to_string(),
    })?;
    let dest = dir.join(MANIFEST_FILE);
    let temp = dir.join(format!("{MANIFEST_FILE}.tmp"));
    std::fs::write(&temp, manifest_json(manifest)).map_err(|e| BuildError::Write {
        path: temp.display().to_string(),
        message: e.to_string(),
    })?;
    std::fs::rename(&temp, &dest).map_err(|e| BuildError::Write {
        path: dest.display().to_string(),
        message: e.to_string(),
    })?;
    Ok(dest)
}

